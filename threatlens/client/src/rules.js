// Turns an indicator into ready-to-deploy detection and blocking rules for common security tools.

function sid(value) {
  // Stable Suricata signature id in the local-rules range (1,000,000 - 1,999,999), derived from the IOC
  let h = 0;
  for (const ch of value) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return 1000000 + (h % 1000000);
}

const HASH_ALGO = { 32: "md5", 40: "sha1", 64: "sha256" };

export function buildRules(report) {
  const { query, type, risk } = report;
  const today = new Date().toISOString().slice(0, 10);
  const label = `ThreatLens ${risk.level.toLowerCase()} ${type}`;
  const rules = [];

  if (type === "ip") {
    const ip = query;
    rules.push(
      {
        tool: "Firewall",
        lang: "bash",
        code: `# Linux (iptables)
iptables -I INPUT  -s ${ip} -j DROP
iptables -I OUTPUT -d ${ip} -j DROP

# Windows (PowerShell, run as Administrator)
New-NetFirewallRule -DisplayName "ThreatLens block ${ip}" -Direction Inbound  -RemoteAddress ${ip} -Action Block
New-NetFirewallRule -DisplayName "ThreatLens block ${ip}" -Direction Outbound -RemoteAddress ${ip} -Action Block`,
      },
      {
        tool: "Suricata / Snort",
        lang: "suricata",
        code: `alert ip $HOME_NET any -> ${ip} any (msg:"${label}: outbound traffic to ${ip}"; classtype:trojan-activity; sid:${sid(ip)}; rev:1;)
alert ip ${ip} any -> $HOME_NET any (msg:"${label}: inbound traffic from ${ip}"; classtype:trojan-activity; sid:${sid(ip) + 1}; rev:1;)`,
      },
      {
        tool: "Sigma",
        lang: "yaml",
        code: `title: Network connection to ${risk.level.toLowerCase()} IP ${ip}
status: experimental
description: Generated by ThreatLens on ${today}. Risk score ${risk.score ?? "n/a"}/100.
logsource:
  category: firewall
detection:
  selection:
    - dst_ip: '${ip}'
    - src_ip: '${ip}'
  condition: selection
level: ${risk.level === "Malicious" ? "high" : "medium"}`,
      },
      {
        tool: "Splunk",
        lang: "spl",
        code: `index=* (src_ip="${ip}" OR dest_ip="${ip}" OR src="${ip}" OR dest="${ip}")
| stats count min(_time) as first_seen max(_time) as last_seen by src, dest, sourcetype
| convert ctime(first_seen) ctime(last_seen)`,
      },
      {
        tool: "Microsoft KQL",
        lang: "kql",
        code: `// Microsoft Defender XDR / Sentinel
DeviceNetworkEvents
| where RemoteIP == "${ip}"
| project Timestamp, DeviceName, InitiatingProcessFileName, RemoteIP, RemotePort, ActionType
| order by Timestamp desc`,
      }
    );
  }

  if (type === "domain" || type === "url") {
    const host = type === "url" ? new URL(query).hostname : query;
    rules.push(
      {
        tool: "DNS block",
        lang: "bash",
        code: `# hosts file / Pi-hole / DNS sinkhole
0.0.0.0 ${host}

# Windows DNS Server (PowerShell): sinkhole the domain
Add-DnsServerQueryResolutionPolicy -Name "ThreatLens-${host}" -Action IGNORE -FQDN "EQ,${host},*.${host}"`,
      },
      {
        tool: "Suricata / Snort",
        lang: "suricata",
        code: `alert dns $HOME_NET any -> any any (msg:"${label}: DNS lookup for ${host}"; dns.query; content:"${host}"; nocase; endswith; classtype:trojan-activity; sid:${sid(host)}; rev:1;)
alert tls $HOME_NET any -> any any (msg:"${label}: TLS connection to ${host}"; tls.sni; content:"${host}"; nocase; endswith; classtype:trojan-activity; sid:${sid(host) + 1}; rev:1;)`,
      },
      {
        tool: "Sigma",
        lang: "yaml",
        code: `title: DNS query for ${risk.level.toLowerCase()} domain ${host}
status: experimental
description: Generated by ThreatLens on ${today}. Risk score ${risk.score ?? "n/a"}/100.
logsource:
  category: dns
detection:
  selection:
    query|endswith: '${host}'
  condition: selection
level: ${risk.level === "Malicious" ? "high" : "medium"}`,
      },
      {
        tool: "Splunk",
        lang: "spl",
        code: `index=* (query="*${host}" OR url="*${host}*" OR dest_host="*${host}")
| stats count min(_time) as first_seen by src, query, url, sourcetype`,
      },
      {
        tool: "Microsoft KQL",
        lang: "kql",
        code: `// Endpoints that contacted it
DeviceNetworkEvents
| where RemoteUrl has "${host}"
| project Timestamp, DeviceName, InitiatingProcessFileName, RemoteUrl, RemoteIP
${type === "url" ? `
// Emails that contained the link (Defender for Office 365)
EmailUrlInfo
| where Url has "${host}"
| join kind=inner EmailEvents on NetworkMessageId
| project Timestamp, RecipientEmailAddress, SenderFromAddress, Subject, Url` : ""}`,
      }
    );
  }

  if (type === "hash") {
    const algo = HASH_ALGO[query.length];
    const psAlgo = algo.toUpperCase();
    rules.push(
      {
        tool: "YARA",
        lang: "yara",
        code: `import "hash"

rule ThreatLens_${query.slice(0, 12)}
{
    meta:
        description = "${label} - ${report.virustotal?.threatLabel || "known malicious file"}"
        author = "ThreatLens"
        date = "${today}"
        ${algo} = "${query}"
    condition:
        hash.${algo}(0, filesize) == "${query}"
}`,
      },
      {
        tool: "Endpoint sweep",
        lang: "powershell",
        code: `# Windows: find the file anywhere under C:\\Users
Get-ChildItem -Path C:\\Users -Recurse -File -ErrorAction SilentlyContinue |
  Get-FileHash -Algorithm ${psAlgo} |
  Where-Object Hash -eq "${query.toUpperCase()}"

# Linux / macOS
find / -type f -size -50M -exec ${algo}sum {} + 2>/dev/null | grep -i ${query}`,
      },
      {
        tool: "Sigma",
        lang: "yaml",
        code: `title: Execution of known malicious file ${query.slice(0, 12)}…
status: experimental
description: Generated by ThreatLens on ${today}. ${report.virustotal?.threatLabel || ""}
logsource:
  product: windows
  category: process_creation
detection:
  selection:
    Hashes|contains: '${psAlgo}=${query.toUpperCase()}'
  condition: selection
level: high`,
      },
      {
        tool: "Splunk",
        lang: "spl",
        code: `index=* ("${query}" OR file_hash="${query}" OR ${algo}="${query}")
| stats count by host, file_name, file_path, sourcetype`,
      },
      {
        tool: "Microsoft KQL",
        lang: "kql",
        code: `DeviceFileEvents
| where ${algo === "md5" ? "MD5" : algo === "sha1" ? "SHA1" : "SHA256"} == "${query}"
| project Timestamp, DeviceName, FileName, FolderPath, ActionType, InitiatingProcessFileName`,
      }
    );
  }

  return rules;
}
